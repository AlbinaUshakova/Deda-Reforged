function phrase(
  ge_text: string,
  ru_meaning: string,
  note?: string,
  accepted_ru?: string[],
  playable?: boolean,
  transcription_en?: string,
): EpisodeCard {
  return {
    type: 'word',
    ge_text,
    ru_meaning,
    ...(accepted_ru?.length ? { accepted_ru } : {}),
    ...(note ? { info_notes: [{ kind: 'grammar' as const, text: note }] } : {}),
    ...(playable === false ? { playable: false } : {}),
    ...(transcription_en ? { transcription_en } : {}),
  };
}

function enPhrase(
  ge_text: string,
  translit: string,
  ru_meaning: string,
  note?: string,
  accepted_ru?: string[],
  playable?: boolean,
  transcription_en?: string,
): EpisodeCard {
  return {
    ...phrase(ge_text, ru_meaning, note, accepted_ru, playable, transcription_en),
    translit,
    transcription_ru: translit,
  };
}

function intentPhrase(
  intent_id: string,
  ge_text: string,
  ru_meaning: string,
  note?: string,
  accepted_ru?: string[],
  playable?: boolean,
  transcription_en?: string,
): EpisodeCard {
  return {
    ...phrase(ge_text, ru_meaning, note, accepted_ru, playable, transcription_en),
    intent_id,
  };
}

function intentEnPhrase(
  intent_id: string,
  ge_text: string,
  translit: string,
  ru_meaning: string,
  note?: string,
  accepted_ru?: string[],
  playable?: boolean,
  transcription_en?: string,
): EpisodeCard {
  return {
    ...enPhrase(ge_text, translit, ru_meaning, note, accepted_ru, playable, transcription_en),
    intent_id,
  };
}

